// Isolated PostgreSQL tests. Never connects to the hosted database.
import {readFile,readdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const {PGlite}=await import(pathToFileURL(process.env.PORTAL_PGLITE_MODULE).href);
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create role service_role;create schema auth;
create table auth.users(id uuid primary key);
create table auth.sessions(id uuid primary key,user_id uuid,created_at timestamptz default now());
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create function auth.jwt() returns jsonb language sql stable as $$select jsonb_build_object('session_id',current_setting('request.jwt.claim.sub',true))$$;
grant usage on schema auth to authenticated;grant execute on all functions in schema auth to authenticated;`);
const migrations=new URL('../supabase/migrations/',import.meta.url);
const files=(await readdir(migrations)).filter(f=>f.endsWith('.sql')).sort();
const latest=files.find(f=>f.endsWith('_portal_attendance_edit_window.sql'));
for(const file of files.filter(f=>f!==latest)) await db.exec(await readFile(new URL(file,migrations),'utf8'));
const id=n=>`00000000-0000-4000-8000-${String(n).padStart(12,'0')}`;
const [trainer,admin,second,outsider,member,guest,group,otherGroup,session]=Array.from({length:9},(_,i)=>id(i+1));
await db.exec(`insert into auth.users values('${trainer}'),('${admin}'),('${second}'),('${outsider}');
insert into portal_staff(id,name,role) values('${trainer}','Coach','trainer'),('${admin}','Admin','admin'),('${second}','Second','trainer'),('${outsider}','Outsider','trainer');
insert into auth.sessions(id,user_id) select id,id from portal_staff;
insert into portal_private.device_sessions(id,user_id,started_at,expires_at,remembered) select id,id,now(),now()+interval '1 hour',false from portal_staff;
insert into portal_groups(id,label,season,level) values('${group}','Test','2026/27','beginner'),('${otherGroup}','Other','2026/27','advanced');
insert into portal_members(id,name,group_id) values('${member}','Test member','${group}'),('${guest}','Late guest','${otherGroup}');
insert into portal_memberships(member_id,group_id,valid_from,source) values('${member}','${group}',current_date-10,'test'),('${guest}','${otherGroup}',current_date-10,'test');
insert into portal_sessions(id,group_id,date,starts,ends,regular_coach_id,coach_id) values('${session}','${group}',current_date-3,'20:00','21:00','${trainer}','${trainer}');
insert into portal_additional_coaches values('${session}','${second}','${second}');`);
async function login(who){await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[who]);await db.exec('set role authenticated');}
const entries=[{member_id:member,status:'absent',kind:'regular'}];
const save=(version,changes={})=>db.query('select public.portal_close_session($1) as s',[{session_id:session,version,entries,comment:'Test',...changes}]).then(r=>r.rows[0].s);
await login(trainer);await save(0);
await login(admin);await save(1);
await db.exec('reset role');
await db.exec(`update portal_audit set recorded_at=now()-interval '24 hours' where session_id='${session}' and before_value->>'status'='planned';`);
const original=(await db.query(`select min(recorded_at)::text as t from portal_audit where session_id='${session}'`)).rows[0].t;
await db.exec(await readFile(new URL(latest,migrations),'utf8'));
assert.equal((await db.query(`select first_saved_at::text as t from portal_sessions where id='${session}'`)).rows[0].t,original);
// A second assigned coach can correct attendance and add a late makeup member.
await login(second);
let s=await save(2,{entries:[{...entries[0],status:'present'},{member_id:guest,status:'present',kind:'makeup'}]});
assert.equal(s.entries.length,2);assert.equal(s.entries[0].status,'present');
const first=s.first_saved_at;
await login(trainer);s=await save(3);assert.equal(s.first_saved_at,first);
await assert.rejects(()=>save(3),/conflict/);
await login(outsider);await assert.rejects(()=>save(4),/unauthorized/);
await db.exec('reset role');
assert.equal((await db.query('select count(*)::int as n from portal_outbox')).rows[0].n,1);
assert.equal((await db.query("select count(*)::int as n from portal_sessions where status='closed'")).rows[0].n,1);
await db.exec(`update portal_sessions set first_saved_at=clock_timestamp()-interval '48 hours'+interval '10 seconds' where id='${session}'`);
await login(trainer);s=await save(4);
await db.exec('reset role');
await db.exec(`update portal_sessions set first_saved_at=clock_timestamp()-interval '48 hours' where id='${session}'`);
await login(trainer);await assert.rejects(()=>save(5),/48 ur/);
await login(admin);s=await save(5);assert.equal(s.version,6);
await db.exec('reset role');
await db.exec(`update portal_sessions set first_saved_at=null where id='${session}'`);
await login(trainer);await assert.rejects(()=>save(6),/48 ur/);
await login(admin);s=await save(6);assert.equal(s.first_saved_at,null);
await db.exec('reset role');
// Fresh first save stamps server time; caller cannot supply a timestamp.
await db.exec(`update portal_sessions set status='planned',entries='[]',comment='',version=7 where id='${session}'`);
await login(trainer);s=await save(7,{first_saved_at:'2099-01-01T00:00:00Z'});
assert.ok(Math.abs(Date.parse(s.first_saved_at)-Date.now())<10000);
await db.exec('reset role');
await db.exec('set role anon');await assert.rejects(()=>save(8),/permission denied/);
await db.close();
console.log('PASS: original audit backfill, late arrival and makeup, both coaches, stable first save, 48h boundary, admin override, cross-coach/anonymous rejection, stale versions, no duplicate mail or hours, server-owned timestamp.');
